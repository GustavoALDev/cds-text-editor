// Agrupa o Markdown do api-documenter (um arquivo por item/membro) numa página por entry
// (spec 07c, X5): `api/core-html` com índice no topo, âncora por item e por membro, links
// `./x.y.md` reescritos para `api/<entry>#<âncora>`, membros `ɵ*` e itens `@internal` omitidos.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { slug } from './slug.mjs';

export const REPO_URL = 'https://github.com/GustavoALDev/cds-text-editor'; // TODO-AUTOR: organização final

/** `rte-core-html` -> `core-html` (id da página: `api/core-html`). */
export const apiPageId = (synthetic) => `api/${synthetic.replace(/^rte-/, '')}`;

const GENERATED = /^<!--\s*Do not edit this file[\s\S]*?-->\s*/;
const FENCE = /^( {0,3})(`{3,}|~{3,})/;
const LINK = /\[((?:\\.|[^\]\\])*)\]\(\.\/([^)\s#]+?)\.md(#[^)\s]*)?\)/g;

const anchorOf = (stem, synthetic) =>
  stem.slice(synthetic.length + 1).replace(/_/g, '');

/** Linhas fora de blocos cercados são transformadas por `fn`. */
function mapOutsideFences(text, fn) {
  let fence = null;
  return text
    .split('\n')
    .map((line) => {
      const m = FENCE.exec(line);
      if (fence) {
        if (m && m[2][0] === fence[0] && m[2].length >= fence.length)
          fence = null;
        return line;
      }
      if (m) {
        fence = m[2];
        return line;
      }
      return fn(line);
    })
    .join('\n');
}

/** Título do arquivo: a primeira linha `## ...`. */
function headingOf(text) {
  const m = /^## (.+)$/m.exec(text);
  return m ? m[1].trim() : null;
}

function stripHeader(text) {
  return text
    .replace(/\r\n/g, '\n')
    .replace(GENERATED, '')
    .replace(/^\[Home\][^\n]*\n+/, '');
}

function isOmitted(text, title) {
  if (/@internal\b/.test(text)) return true;
  // `Classe.ɵfac property`: algum segmento do nome começa com ɵ.
  const name = (title ?? '').split(/\s/)[0];
  return name.split('.').some((part) => part.startsWith('ɵ'));
}

/**
 * Páginas de API a partir de `markdownDir` (saída do api-documenter).
 * entries: [{ synthetic, specifier }]. Devolve [{ id, specifier, synthetic, title, markdown }].
 */
export function groupApiPages({
  markdownDir,
  entries,
  repoUrl = REPO_URL,
  packageDirOf,
}) {
  const names = readdirSync(markdownDir).filter((f) => f.endsWith('.md'));
  const stems = new Set(names.map((f) => f.slice(0, -3)));
  const bySynthetic = [...entries].sort(
    (a, b) => b.synthetic.length - a.synthetic.length,
  );
  const entryOf = (stem) =>
    bySynthetic.find(
      (e) => stem === e.synthetic || stem.startsWith(`${e.synthetic}.`),
    );

  const contents = new Map();
  for (const stem of stems)
    contents.set(
      stem,
      stripHeader(readFileSync(join(markdownDir, `${stem}.md`), 'utf8')),
    );
  const omitted = new Set();
  for (const [stem, text] of contents) {
    const e = entryOf(stem);
    if (!e || stem === e.synthetic) continue;
    if (isOmitted(text, headingOf(text))) omitted.add(stem);
  }
  // membros de um item omitido também saem
  for (const stem of stems) {
    const e = entryOf(stem);
    if (!e || stem === e.synthetic) continue;
    const parts = stem.slice(e.synthetic.length + 1).split('.');
    if (parts.length > 1 && omitted.has(`${e.synthetic}.${parts[0]}`))
      omitted.add(stem);
  }

  const rewriteLinks = (text, where) =>
    text.replace(LINK, (_, label, stem, hash) => {
      void hash;
      const target = entryOf(stem);
      if (!stems.has(stem) || !target) {
        if (stem === 'index') return label;
        throw new Error(
          `${where}: link para "${stem}.md" sem arquivo/entry correspondente`,
        );
      }
      if (omitted.has(stem)) return label;
      const anchor =
        stem === target.synthetic ? '' : `#${anchorOf(stem, target.synthetic)}`;
      return `[${label}](${apiPageId(target.synthetic)}${anchor})`;
    });

  const dropOmittedRows = (text) => {
    let out = text.replace(
      /(<tbody>)?<tr><td>[\s\S]*?<\/td><\/tr>\n?/g,
      (row, tbody) => {
        const links = [...row.matchAll(LINK)].map((m) => m[2]);
        return links.some((s) => omitted.has(s)) ? (tbody ?? '') : row;
      },
    );
    out = out.replace(/<table>(?:(?!<td>)[\s\S])*?<\/table>\n*/g, '');
    // títulos que ficaram sem conteúdo (só tabelas de membros omitidos)
    let prev;
    do {
      prev = out;
      out = out.replace(
        /^#{2,6} [^\n]*\n(?:[ \t]*\n)*(?=#{2,6} |(?![\s\S]))/gm,
        '',
      );
    } while (out !== prev);
    return out;
  };

  const demote = (text, by) =>
    mapOutsideFences(text, (line) => {
      const m = /^(#{2,6}) (.+)$/.exec(line);
      return m ? `${'#'.repeat(Math.min(6, m[1].length + by))} ${m[2]}` : line;
    });

  // id explícito em todo título (h2.. do corpo): `<base>-<slug>`, único na página.
  const used = new Set();
  const unique = (id, where) => {
    let candidate = id;
    for (let n = 2; used.has(candidate); n++) candidate = `${id}-${n}`;
    used.add(candidate);
    return candidate;
  };
  const withIds = (text, base, where) =>
    mapOutsideFences(text, (line) => {
      const m = /^(#{2,6}) (.+?)(?: \{#[^}]+\})?$/.exec(line);
      if (!m) return line;
      const id = unique(`${base}-${slug(m[2].replace(/[`\\]/g, ''))}`, where);
      return `${m[1]} ${m[2]} {#${id}}`;
    });

  return entries.map((entry) => {
    const { synthetic, specifier } = entry;
    const id = apiPageId(synthetic);
    used.clear();
    const where = id;
    const entryText = contents.get(synthetic);
    if (entryText === undefined)
      throw new Error(
        `${where}: o api-documenter não gerou ${synthetic}.md (entry sem modelo?)`,
      );

    const parts = [`Especificador de importação: \`${specifier}\`.`];

    // Índice: o corpo do arquivo do entry sem o título `## x package`.
    let index = entryText.replace(/^## .* package\s*\n/m, '');
    index = rewriteLinks(dropOmittedRows(index), where);
    index = demote(index, 1); // ## Functions -> ### Functions
    index = withIds(index, 'indice', where);
    // Título "Índice" some se não sobrar nada além de espaço.
    parts.push(`## Índice {#${unique('indice', where)}}`, '', index.trim());

    // Itens na ordem em que o índice os lista; depois os não listados.
    const listed = [];
    for (const m of entryText.matchAll(LINK)) {
      const stem = m[2];
      const e = entryOf(stem);
      if (
        e?.synthetic === synthetic &&
        stem !== synthetic &&
        !listed.includes(stem)
      )
        listed.push(stem);
    }
    const itemStems = [...stems]
      .filter(
        (s) =>
          entryOf(s)?.synthetic === synthetic &&
          s.slice(synthetic.length + 1).split('.').length === 1 &&
          s !== synthetic,
      )
      .sort();
    for (const s of itemStems) if (!listed.includes(s)) listed.push(s);

    for (const stem of listed) {
      if (omitted.has(stem)) continue;
      const text = contents.get(stem);
      if (text === undefined) continue;
      const itemTitle = headingOf(text);
      const itemAnchor = unique(anchorOf(stem, synthetic), where);
      let body = text.replace(/^## .+\n?/m, '');
      body = rewriteLinks(dropOmittedRows(body), where);
      body = withIds(demote(body, 1), itemAnchor, where);
      parts.push(`## ${itemTitle} {#${itemAnchor}}`, '', body.trim());

      const members = [...stems]
        .filter((s) => s.startsWith(`${stem}.`) && !omitted.has(s))
        .sort();
      // ordem da tabela do item
      const order = [...text.matchAll(LINK)].map((m) => m[2]);
      members.sort((a, b) => {
        const ia = order.indexOf(a);
        const ib = order.indexOf(b);
        return (ia < 0 ? 1e9 : ia) - (ib < 0 ? 1e9 : ib) || a.localeCompare(b);
      });
      for (const mem of members) {
        const mtext = contents.get(mem);
        const mTitle = headingOf(mtext);
        const mAnchor = unique(anchorOf(mem, synthetic), where);
        let mbody = mtext.replace(/^## .+\n?/m, '');
        mbody = rewriteLinks(mbody, where);
        mbody = withIds(demote(mbody, 2), mAnchor, where);
        parts.push(`### ${mTitle} {#${mAnchor}}`, '', mbody.trim());
      }
    }

    const pkgDir = packageDirOf
      ? packageDirOf(synthetic)
      : synthetic.split('-')[1];
    parts.push(
      '---',
      '',
      `Relatório congelado da superfície pública: [${synthetic}.api.md](${repoUrl}/blob/main/packages/${pkgDir}/api/${synthetic}.api.md).`,
    );
    return {
      id,
      synthetic,
      specifier,
      title: specifier,
      description: `Referência da API de ${specifier}.`,
      markdown: parts.join('\n\n').replace(/\n{3,}/g, '\n\n'),
    };
  });
}

/** Entry publicado sem página, ou página sem entry, falha (mesma lista dos `exports`). */
export function assertCoverage(exportSpecifiers, pages) {
  const have = new Set(pages.map((p) => p.specifier));
  const want = new Set(exportSpecifiers);
  const errors = [];
  for (const s of want)
    if (!have.has(s)) errors.push(`entry publicado "${s}" sem página de API`);
  for (const s of have)
    if (!want.has(s))
      errors.push(`página de API "${s}" sem entry publicado nos exports`);
  if (errors.length)
    throw new Error(
      `cobertura da API (spec 07c, X5):\n  - ${errors.join('\n  - ')}`,
    );
}
